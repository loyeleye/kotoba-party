// What each game gives a player to say from memory, by level: the table the path's suggestion ranks games by
// (shared/src/pathYields.ts). Bots play every game in-process (tools/sim/play.ts, speaking where the game
// allows), and each seat's phrasebook is counted the way the path counts it: a line said from memory adds one to
// every frame phraseFrames finds in it, and a kanji read from memory in a game adds one to "kanji:<level>".
//
//   npm run sim:yields [-- --games 32 --seed 1]     rewrites shared/src/pathYields.ts
//
// Bot gaps show as zeros: a game whose bots can't do what players do yields nothing for that frame here.
// BOT_GAPS in shared/src/path.ts lists the known bot gaps, which count as a slow stop (BOT_GAP_YIELD).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import type { Level } from '../../content/src/types.js';
import { writeKanji } from '../../content/src/kanji/kanji.js';
import { loadContent } from '../../server/src/content.js';
import { MODES } from '../../shared/src/modes/registry.js';
import { MODE_IDS, type ModeId } from '../../shared/src/protocol.js';
import { phraseFrames } from '../../shared/src/progress.js';
import { playGame } from './play.js';

const { values } = parseArgs({ options: { games: { type: 'string', default: '32' }, seed: { type: 'string', default: '1' }, out: { type: 'string' } } });

/** Two rooms of four, so every level gets two seats a game. */
const ROOMS: readonly (readonly Level[])[] = [
  ['n4', 'n4', 'n5', 'n5'],
  ['kana', 'kana', 'n5', 'n5'],
];
const KANJI_LEVEL = new Map(writeKanji.map((k) => [k.char, k.level]));

export type Yields = Partial<Record<Level, Partial<Record<ModeId, Record<string, number>>>>>;

export function measure(games: number, seed: number): Yields {
  const content = loadContent(fileURLToPath(new URL('../../', import.meta.url)));
  const out: Yields = {};
  for (const mode of MODE_IDS) {
    if (mode === 'debug') continue;
    const info = MODES[mode].info;
    for (const levels of ROOMS) {
      if (levels.length < info.minPlayers || levels.length > info.maxPlayers) continue;
      const sums = new Map<Level, { seats: number; frames: Record<string, number> }>();
      for (let i = 0; i < games; i++) {
        let g;
        try {
          g = playGame(content, mode, levels, seed * 1000 + i + 1);
        } catch {
          continue; // no bot policy for this game, or it stalls: it yields nothing here
        }
        for (const s of g.seats) {
          const acc = sums.get(s.level) ?? { seats: 0, frames: {} };
          acc.seats += 1;
          for (const e of s.result.phrases) {
            if (e.outcome !== 'said' || e.recall !== 'memory') continue;
            for (const f of phraseFrames(e)) acc.frames[f] = (acc.frames[f] ?? 0) + 1;
            if (e.itemId.startsWith('kj-')) {
              const lv = KANJI_LEVEL.get(e.itemId.slice(3));
              if (lv) acc.frames[`kanji:${lv}`] = (acc.frames[`kanji:${lv}`] ?? 0) + 1;
            }
          }
          sums.set(s.level, acc);
        }
      }
      for (const [level, acc] of sums) {
        if (!acc.seats || (out[level]?.[mode] && level === 'n5')) continue; // N5 is measured in the first room only
        const per = Object.fromEntries(
          Object.entries(acc.frames)
            .map(([k, v]) => [k, Math.round((v / acc.seats) * 100) / 100] as const)
            .filter(([, v]) => v >= 0.05)
            .sort(([a], [b]) => a.localeCompare(b)),
        );
        (out[level] ??= {})[mode] = per;
      }
    }
  }
  return out;
}

function render(y: Yields, games: number): string {
  const lines = [
    '// Generated by `npm run sim:yields` (tools/sim/yields.ts): do not edit by hand.',
    `// Frames a player says from memory per game, by level and game, from ${games} bot games per room.`,
    "// Keys are frame ids, plus kanji:<level> for kanji read from memory. Values under 0.05 are left out.",
    '',
    "import type { Level } from '../../content/src/types.js';",
    "import type { ModeId } from './protocol.js';",
    '',
    'export const YIELDS: Readonly<Partial<Record<Level, Partial<Record<ModeId, Readonly<Record<string, number>>>>>>> = ',
  ];
  return `${lines.join('\n')}${JSON.stringify(y, null, 2)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const games = Number(values.games);
  const y = measure(games, Number(values.seed));
  const path = values.out ?? fileURLToPath(new URL('../../shared/src/pathYields.ts', import.meta.url));
  writeFileSync(path, render(y, games));
  console.log(`Wrote ${path}`);
}
