// Builds content/src/kanji/strokes.ts (Shodō Taikai's stroke references) from KanjiVG, for every
// kanji in content/src/kanji/kanji.ts.
//
//   npx tsx tools/content-kanji-strokes.ts [folder-of-svgs]
//
// Same pipeline as tools/content-strokes.ts (kana): each stroke's SVG path is flattened, scaled
// from KanjiVG's 109-unit box to 0–1 and simplified, start → end, in KanjiVG's stroke order
// (which follows the Japanese school order). KanjiVG is © Ulrich Apel, CC BY-SA 3.0; the generated
// file carries the attribution.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { writeKanji } from '../content/src/kanji/kanji.js';
import { BOX, flatten, round, simplify, strokePaths, svgFor, TOLERANCE, type Pt } from './kanjivg.js';

const dir = process.argv[2];
const lines: string[] = [];
for (const k of writeKanji) {
  const paths = strokePaths(svgFor(k.char, dir));
  if (!paths.length) throw new Error(`No strokes for ${k.char}`);
  const strokes = paths.map((d) => simplify(flatten(d).map(([x, y]): Pt => [x / BOX, y / BOX]), TOLERANCE).map(([x, y]) => `[${round(x)}, ${round(y)}]`));
  lines.push(`  { char: '${k.char}', strokes: [${strokes.map((s) => `[${s.join(', ')}]`).join(', ')}] },`);
}

const out = `// GENERATED by tools/content-kanji-strokes.ts from KanjiVG. Do not edit by hand; re-run the tool.
//
// Stroke references for Shodō Taikai (the Calligraphy Contest): every kanji in kanji.ts, strokes
// in standard order, each a simplified polyline from start to end in a 0–1 box (x right, y down).
//
// Derived from KanjiVG (https://kanjivg.tagaini.net), © Ulrich Apel and contributors,
// licensed under Creative Commons Attribution-Share Alike 3.0
// (https://creativecommons.org/licenses/by-sa/3.0/). This derived data is shared under the
// same licence.

import type { CharStrokes } from '../types.js';

export const kanjiStrokes: CharStrokes[] = [
${lines.join('\n')}
];
`;
writeFileSync(fileURLToPath(new URL('../content/src/kanji/strokes.ts', import.meta.url)), out);
console.log(`wrote ${lines.length} kanji`);
