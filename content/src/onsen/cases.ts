// Murder at the Onsen: three hand-written whodunits (backlog mode, shared/src/modes/onsenMurder).
//
// Every fact a suspect can say is written here, so the game never needs an LLM to answer.
// Japanese is N5 level, kana with spaces between words (kana-level players can read it),
// with digits for clock times; `kana` is the full reading the stage voices. The "victims"
// are things, not people (a snowman, a pudding, a rubber duck): the show's tone puts the
// joke on the situation. Every case is `draft` until a fluent speaker checks it.
//
// How a case is built: each suspect answers the six questions (where / what / who / when /
// victim / item). Some answers put a clue in the shared notebook; the key clues together
// point at one culprit, who lies about one thing. Two answers may give the same clue.
//
// Every answer also carries the N4 deputy's `report`: what the suspect said, in reported speech
// (たなかさんは 12じに ねたと いっていました) or, for a sighting, the passive (たなかさんは すずきさんに
// みられました). Words are spaced, because each word is one of the deputy's tiles. A sighting whose
// passive would drop a key fact (holding something, a red face, being angry) is reported as speech.
//
// A case with an `audience` plays only in a room set to it: the ice cream case is a shorter,
// sillier one for Kids; the sake, smartphone, toupee and candle cases (a hangover, a bad date,
// a boss who takes the credit, a ghost-story night) are for Cheeky rooms.

import type { JpText, OnsenCase, OnsenReport } from '../types.js';

const t = (text: string, kana: string, en: string): JpText => ({ text, kana, en });
/** Kana-only Japanese: text and reading are the same. */
const k = (text: string, en: string): JpText => ({ text, kana: text, en });

/**
 * The N4 deputy's report of an answer (the hard role, 4.13 and 4.14). Reported speech, ＿と いっていました,
 * in plain form: `kana` is null when the text is its own reading.
 */
const said = (text: string, kana: string | null, en: string, ...frames: string[]): OnsenReport => ({ jp: kana ? t(text, kana, en) : k(text, en), frames: ['to-itte-ita', ...frames] });
/** The passive report of a "who did you see?" answer: ＿は ＿に みられました. */
const seen = (text: string, kana: string | null, en: string): OnsenReport => ({ jp: kana ? t(text, kana, en) : k(text, en), frames: ['passive'] });
